"""Посчитать и вывести количество элементов арифметической прогрессии,
удовлетворяющих условию 10<ai<30."""

while True:
    try:
        A = float(input("Введите первый элемент: "))
        D = float(input("Введите разность: "))
        N = int(input("Введите количество элементов: "))

        if N > 0:
            break
        else:
            print("Ошибка! N должно быть больше 0.")
    except ValueError:
        print("Ошибка! Введите правильные данные.")

K = 0
I = 0

while I < N:
    if A > 10 and A < 30:
        K += 1

    A += D
    I += 1

print("Количество элементов:", K)