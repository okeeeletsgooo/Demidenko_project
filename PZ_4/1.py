"""1. Ввести 4 числа. Найти и вывести на экран сумму и количество отрицательных
чисел."""

S = 0
K = 0

for I in range(4):
    while True:
        try:
            A = float(input("Введите число: "))
            break
        except ValueError:
            print("Ошибка! Введите число.")

    if A < 0:
        S = S + A
        K = K + 1

print("Сумма отрицательных:", S)
print("Количество отрицательных:", K)