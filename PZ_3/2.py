"""2. Ввести число. Если оно чётное, разделить его на 4, если нечётное — умножить на 5."""

while True:
    try:
        A = int(input("Введите число: "))
        break
    except ValueError:
        print("Ошибка! Введите целое число.")

if A % 2 == 0:
    A = A / 4
else:
    A = A * 5

print("Результат:", A)