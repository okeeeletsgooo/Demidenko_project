"""Дано целое число. Если оно положительное, прибавить к нему 20, в противном случае вычесть из него 5."""

while True:
    try:
        A = int(input("Введите число: "))
        break
    except ValueError:
        print("Ошибка! Введите целое число.")

if  A > 0:
     A = A + 20
else:
     A = A - 5

print("Результат:", A)