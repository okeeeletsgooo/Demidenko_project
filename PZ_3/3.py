"""Ввести двузначное число. Если сумма цифр числа чётная, увеличить число на 2, в противном случае уменьшить на 2."""

while True:
    try:
        A = int(input("Введите двузначное число: "))
        if A >= 10 and A <= 99:
            break
        else:
            print("Ошибка! Введите двузначное число.")
    except ValueError:
        print("Ошибка! Введите целое число.")

B = A // 10
C = A % 10

if (B + C) % 2 == 0:
    A = A + 2
else:
    A = A - 2

print("Результат:", A)