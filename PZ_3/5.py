"""5. Дано два числа. Если их сумма кратна 5, прибавить 1, иначе вычесть 2."""

while True:
    try:
        A = int(input("Введите первое число: "))
        B = int(input("Введите второе число: "))
        break
    except ValueError:
        print("Ошибка! Введите целые числа.")

C = A + B

if C % 5 == 0:
    C = C + 1
else:
    C = C - 2

print("Результат:", C)